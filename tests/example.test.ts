test('the actual high-detail world example generates all five settlements, meaningful layers, safe sea routes and a valid saved workspace', () => {
  const data = createExampleWorkspace(),
    map = data.maps[0],
    original = structuredClone(map);
  const editor = map.editor!,
    recipe = editor.generation as SketchGenerationV2;
  const result = generateSketchMap(
    editor.regions,
    map.width,
    map.height,
    recipe,
    map.scaleKm,
    map.kind,
  );
  assert.deepEqual(map, original, 'generation must not mutate the authored example');
  assert(result.geography && result.elevation && result.sites);
  assert.equal(result.sites.length, 12);
  assert.deepEqual(
    new Set(result.sites.map((site) => site.kind)),
    new Set(Object.keys(settlementCatalog)),
  );
  for (const site of result.sites) {
    assert.equal(site.name, recipe.settlementNames![site.id]);
    assert.equal(site.entityId, recipe.settlementLinks![site.id]);
  }
  const geography = result.geography,
    land = geography.cells.filter((cell) => cell.land);
  assert(land.length > 0 && land.length < geography.cells.length);
  assert.equal(geography.plates.length, recipe.geography!.plateCount);
  for (const [kind, count] of [
    ['country', 4],
    ['culture', 4],
    ['religion', 3],
  ] as const) {
    assert.equal(geography.divisions.filter((division) => division.kind === kind).length, count);
    assert(land.every((cell) => cell[kind]));
  }
  assert(new Set(land.map((cell) => cell.biome)).size >= 6);
  assert(land.every((cell) => cell.temperature > -45 && cell.temperature < 25));
  assert(land.every((cell) => cell.precipitation >= 0 && cell.precipitation < 6000));
  assert(Math.max(...land.map((cell) => cell.precipitation)) > 1000);
  assert(Math.max(...land.map((cell) => cell.temperature)) > 10);
  assert(geography.areas.some((area) => area.kind === 'ocean'));
  assert(geography.areas.some((area) => area.kind === 'province'));
  assert(geography.borders.some((border) => border.kind === 'country'));
  assert(result.stats.rivers > 0 && result.stats.roads > 0);
  const surface = snapshotElevation(result.elevation)!;
  assert(geography.ports.length >= 2 && geography.seaRoutes.length >= 1);
  for (const port of geography.ports) {
    assert(geography.cells[port.cell].land);
    assert(isWaterPoint(surface, port.harbor, -5));
  }
  for (const route of geography.seaRoutes) {
    assert(geography.ports.some((port) => port.id === route.from));
    assert(geography.ports.some((port) => port.id === route.to));
    assert(route.points.length > 2);
    for (let index = 0; index < route.points.length; index++) {
      assert(isWaterPoint(surface, route.points[index], -5));
      if (index) assert(isWaterSegment(surface, route.points[index - 1], route.points[index], -5));
    }
  }
  editor.generated = {
    version: 1,
    signature: generationSignature(
      editor.regions,
      map.width,
      map.height,
      recipe,
      map.scaleKm,
      map.kind,
    ),
    objects: result.objects,
    stats: result.stats,
    sites: result.sites,
    elevation: surface,
    geography,
  };
  const associated = associateGeographicDivisions(map, data.entities, {
    world: data.worlds[0],
    canCreate: true,
  });
  assert.equal(associated.unlinked, 0);
  assert.equal(
    associated.entities.length,
    0,
    'existing story factions, cultures and religions cover this example',
  );
  data.maps[0] = associated.map;
  for (const division of associated.map.editor!.generated!.geography!.divisions)
    assert(
      data.entities.some(
        (entity) => entity.id === division.entityId && entity.name === division.name,
      ),
    );
  const portable = JSON.parse(JSON.stringify(data));
  assert.deepEqual(validateWorkspace(portable), portable);
});
