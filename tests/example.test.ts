test('installation examples use complete modern recipes and location names without duplicate story markers', () => {
  const data = createExampleWorkspace();
  assert.deepEqual(validateWorkspace(data), data);
  assert.deepEqual(data, createExampleWorkspace());
  assert.equal(new Set(data.maps.map((map) => map.seed)).size, 4);
  const sketchShapes = new Set<string>();
  for (const map of data.maps) {
    const editor = map.editor!,
      recipe = editor.generation as SketchGenerationV2;
    assert.equal(recipe.version, 2);
    assert.equal(recipe.detail, 'high');
    assert.equal(recipe.linework, 'organic');
    assert.equal(recipe.seed, map.seed);
    assert.equal(recipe.elevation?.preset, 'sketch');
    assert.equal(recipe.elevation.seed, map.seed);
    assert.deepEqual(recipe.elevation.strokes, []);
    assert(recipe.geography && recipe.geography.source === 'sketch');
    assert(recipe.rivers && recipe.routes);
    assert.equal(editor.divisionPaint, undefined, 'do not use old circular division painting');
    assert(editor.divisions?.some((division) => division.kind === 'country' && division.entityId));
    assert.match(map.summary, /地名与地点/);
    assert.match(map.summary, /剧情/);
    assert.equal(
      editor.generated,
      undefined,
      'new-install recipes are generated by the existing snapshot workflow',
    );
    const plan = settlementPlan(recipe),
      plannedIds = new Set(plan.map((site) => site.id));
    assert.equal(plan.length, recipe.settlements);
    assert.deepEqual(Object.keys(recipe.settlementNames!).sort(), [...plannedIds].sort());
    assert.equal(new Set(plan.map((site) => site.name)).size, plan.length);
    const markerNames = new Set(map.pins.map((pin) => pin.label));
    for (const site of plan)
      assert(!markerNames.has(site.name), `${map.name}: duplicate ${site.name}`);
    assert(Object.keys(recipe.settlementLinks!).length > 0);
    for (const [siteId, entityId] of Object.entries(recipe.settlementLinks!)) {
      assert(plannedIds.has(siteId));
      const entity = data.entities.find((candidate) => candidate.id === entityId);
      assert(entity && entity.type === 'location' && entity.worldId === map.worldId);
      if (map.kind !== 'town') assert.equal(recipe.settlementNames![siteId], entity.name);
    }
    sketchShapes.add(
      JSON.stringify(
        editor.regions.map(({ biome, geometry, points, width }) => ({
          biome,
          geometry,
          points,
          width,
        })),
      ),
    );
  }
  assert.equal(sketchShapes.size, 4, 'each map demonstrates a different terrain composition');
  const world = data.maps[0].editor!.generation as SketchGenerationV2;
  assert.equal(settlementPlan(world).length, 12);
  assert.deepEqual(
    new Set(settlementPlan(world).map((site) => site.kind)),
    new Set(Object.keys(settlementCatalog)),
  );
});

test('local climate extents match each example map scale instead of stretching towns across the globe', () => {
  const maps = createExampleWorkspace().maps;
  assert.deepEqual(
    maps.map((map) => map.scaleKm),
    [1800, 240, 4, 7],
  );
  for (const map of maps) {
    const settings = (map.editor!.generation as SketchGenerationV2).geography!;
    const latitude = (settings.latitudeNorth + settings.latitudeSouth) / 2;
    assert(latitude > 30 && latitude < 40);
    const northSouthKm = (settings.latitudeNorth - settings.latitudeSouth) * 111.32;
    const eastWestKm =
      (settings.longitudeEast! - settings.longitudeWest!) *
      111.32 *
      Math.cos((latitude * Math.PI) / 180);
    assert(Math.abs(eastWestKm - map.scaleKm!) < 1e-8);
    assert(Math.abs(northSouthKm - (map.scaleKm! * map.height) / map.width) < 1e-8);
    const northTemperature = geographicTemperature(
      settings.latitudeNorth,
      0,
      settings.meanSeaTemperature,
    );
    const southTemperature = geographicTemperature(
      settings.latitudeSouth,
      0,
      settings.meanSeaTemperature,
    );
    assert(northTemperature > 5 && southTemperature < 20);
    if (map.kind === 'town') assert(southTemperature - northTemperature < 0.03);
  }
});

